#!/usr/bin/env node
// scripts/generate-hook-allowlist.mjs
//
// v2.15.0 — Wave A Deliverable: Auto-generate default-deny allowlist from registry.
// Per Security Council report H3: "PreToolUse default-deny allowlist is hand-maintained".
//
// Reads:  registry/agents.json (canonical tool inventory)
// Writes: .claude/hooks/pre-tool-use-default-deny.mjs (regenerated allowlist)
//
// Usage:  node scripts/generate-hook-allowlist.mjs [--out <path>] [--dry-run]

import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, '..');

// ---------- Args ----------
const args = process.argv.slice(2);
const dryRun = args.includes('--dry-run');
const outIdx = args.indexOf('--out');
const OUT = outIdx !== -1 ? args[outIdx + 1] : join(ROOT, '.claude/hooks/pre-tool-use-default-deny.mjs');

// ---------- Load canonical tool inventory ----------
const agentsPath = join(ROOT, 'registry/agents.json');
if (!existsSync(agentsPath)) {
  console.error(`FATAL: ${agentsPath} not found. Cannot generate allowlist.`);
  process.exit(1);
}

const agents = JSON.parse(readFileSync(agentsPath, 'utf8'));
// agents.json is a registry of SUBAGENT personas (architect, implementer, ...),
// not Claude Code tools (Read, Edit, Bash, ...). The hook allowlist covers tools.
// Filter to entries that look like tools (CamelCase or contain 'tool') so the
// warning is meaningful, not noisy.
const toolNames = (agents.agents || [])
  .map(a => a.name)
  .filter(Boolean)
  .filter(n => /[A-Z]/.test(n) || n.includes('tool'));

// Curated allowlist (security posture) — extends registry-derived list with explicit allow + block
const TOOL_ALLOWLIST = {
  // Read-only exploration — always allowed
  Read:    { actions: ['*'], reason: 'read-only' },
  Grep:    { actions: ['*'], reason: 'read-only' },
  Glob:    { actions: ['*'], reason: 'read-only' },
  LS:      { actions: ['*'], reason: 'read-only' },

  // Editing — allowed but logged (PostToolUse secret scan runs on Edit/Write)
  Edit:        { actions: ['*'], reason: 'editing tracked files (PostToolUse secret scan via v2.14.0 redactor)' },
  Write:       { actions: ['*'], reason: 'writing tracked files (PostToolUse secret scan via v2.14.0 redactor)' },
  MultiEdit:   { actions: ['*'], reason: 'multi-edit (PostToolUse secret scan)' },

  // Bash — explicit command allowlist
  Bash: { actions: [
    'npm test', 'npm run test', 'npm run validate', 'npm run validate:all',
    'npm run quality:engine', 'npm run dashboard:generate',
    'git status', 'git log', 'git diff', 'git show', 'git branch', 'git add', 'git commit',
    'ls', 'pwd', 'cat', 'head', 'tail', 'wc', 'file',
    'node --version', 'npm --version',
  ], reason: 'allowlisted commands' },

  // Web — restricted to allowlisted domains
  WebFetch:  { actions: ['github.com', 'raw.githubusercontent.com', 'npmjs.com', 'docs.*'], reason: 'allowlisted domains' },
  WebSearch: { actions: ['*'], reason: 'web search (logged)' },

  // Agent delegation — restricted to read-only subagent tasks
  Task: { actions: ['explore', 'plan'], reason: 'read-only subagent tasks' },

  // Memory — restricted, audited
  memory_read:  { actions: ['*'], reason: 'memory read (logged)' },
  memory_write: { actions: ['*'], reason: 'memory write (logged + audited)' },
};

// Destructive blocklist — always denied regardless of allowlist
const TOOL_BLOCKLIST_OVERRIDE = {
  Bash: [
    'rm -rf', 'rm -fr', 'rm -R', 'rm -r /',
    'dd if=', 'mkfs', 'fdisk', 'shutdown', 'reboot', 'halt', 'poweroff',
    ':(){:|:&};:',
    'curl | bash', 'wget | bash', 'curl | sh', 'wget | sh',
    'chmod 777', 'chown -R',
    '> /dev/sd', '> /dev/nvme',
    'iptables -F', 'ufw disable',
    'eval $(',
    'curl -X POST', 'wget --post-data',
  ],
};

// Detect tools referenced in registry but missing from allowlist
const knownTools = new Set(Object.keys(TOOL_ALLOWLIST));
const registryTools = new Set(toolNames);
const missing = [...registryTools].filter(t => !knownTools.has(t));
if (missing.length > 0) {
  console.warn(`WARN: ${missing.length} tools in registry/agents.json not in allowlist:`);
  missing.forEach(t => console.warn(`  - ${t}`));
  console.warn(`Run: node scripts/generate-hook-allowlist.mjs to add them.`);
}

// ---------- Render ----------
function render() {
  return `#!/usr/bin/env node
// .claude/hooks/pre-tool-use-default-deny.mjs
//
// v2.15.0 — AUTO-GENERATED by scripts/generate-hook-allowlist.mjs from registry/agents.json.
// DO NOT EDIT — run \`node scripts/generate-hook-allowlist.mjs\` to regenerate.
//
// Default-deny guard for Claude Code. Blocks ALL tool calls unless the
// (tool_name, action) pair is explicitly allowlisted.
// Per Wave A Deliverable: "Wire the Shield" — auto-generate allowlist from canonical inventory.
// Project-trusted hooks path (.claude/hooks/), NOT userland (~/.claude/hooks/).

const TOOL_ALLOWLIST = ${JSON.stringify(TOOL_ALLOWLIST, null, 2)};

const TOOL_BLOCKLIST_OVERRIDE = ${JSON.stringify(TOOL_BLOCKLIST_OVERRIDE, null, 2)};

let input = '';
process.stdin.on('data', c => input += c);
process.stdin.on('end', () => {
  try {
    const data = JSON.parse(input);
    const tool = data.tool_name || data.name || 'unknown';
    const input_data = data.tool_input || data.input || {};
    const action = inferAction(tool, input_data);

    const allowed = TOOL_ALLOWLIST[tool];
    if (!allowed) {
      deny(tool, action, 'tool not in allowlist (default-deny)');
      return;
    }
    if (allowed.actions[0] !== '*' && !allowed.actions.includes(action)) {
      deny(tool, action, \`action '\${action}' not in allowlist for tool '\${tool}'\`);
      return;
    }

    const overrides = TOOL_BLOCKLIST_OVERRIDE[tool];
    if (overrides) {
      for (const blocked of overrides) {
        if (action.includes(blocked)) {
          deny(tool, action, \`blocked by override pattern: '\${blocked}'\`);
          return;
        }
      }
    }

    process.stdout.write(JSON.stringify({ decision: 'allow', reason: allowed.reason }));
    process.exit(0);
  } catch (e) {
    deny('parse-error', '', 'malformed hook input: ' + e.message);
  }
});

function inferAction(tool, input) {
  if (tool === 'Bash') return input.command || '';
  if (tool === 'Edit' || tool === 'Write' || tool === 'MultiEdit') return input.file_path || '';
  if (tool === 'Read') return input.file_path || '';
  if (tool === 'WebFetch') return input.url || '';
  return JSON.stringify(input).slice(0, 200);
}

function deny(tool, action, reason) {
  process.stdout.write(JSON.stringify({
    decision: 'deny',
    reason,
    tool,
    action: action.slice(0, 200)
  }));
  process.exit(2);
}
`;
}

const rendered = render();
if (dryRun) {
  console.log(rendered);
} else {
  writeFileSync(OUT, rendered, 'utf8');
  console.log(`Wrote ${OUT} (${rendered.length} bytes)`);
  console.log(`Allowlist covers ${Object.keys(TOOL_ALLOWLIST).length} tools from registry.`);
  if (missing.length > 0) {
    console.log(`\nNOTE: ${missing.length} tools in registry/agents.json are NOT in the curated allowlist.`);
    console.log(`Add them to TOOL_ALLOWLIST in scripts/generate-hook-allowlist.mjs and rerun.`);
  }
}
